#!/usr/bin/env python3
"""Regenerate vectors.inc from vectors.txt with devkitPPC's GNU assembler as the reference."""

import os
import subprocess
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
DEVKITPPC = os.environ.get("DEVKITPPC", "/opt/devkitpro/devkitPPC")
AS = os.path.join(DEVKITPPC, "bin", "powerpc-eabi-as")
OBJCOPY = os.path.join(DEVKITPPC, "bin", "powerpc-eabi-objcopy")


def gas_line(line):
    mnemonic, _, ops = line.partition(" ")
    if not mnemonic.startswith("b") or not ops or mnemonic in ("blr", "blrl", "bctr", "bctrl"):
        return line
    parts = [p.strip() for p in ops.split(",")]
    parts[-1] = ".+(" + parts[-1] + ")"
    return mnemonic + " " + ", ".join(parts)


def main():
    lines = []
    with open(os.path.join(HERE, "vectors.txt")) as f:
        for raw in f:
            raw = raw.strip()
            if raw and not raw.startswith("#"):
                lines.append(raw)

    with tempfile.TemporaryDirectory() as tmp:
        src = os.path.join(tmp, "v.s")
        obj = os.path.join(tmp, "v.o")
        bin_ = os.path.join(tmp, "v.bin")
        with open(src, "w") as f:
            f.write("\n".join(gas_line(l) for l in lines) + "\n")
        subprocess.run([AS, "-mregnames", "-mbig", "-m750cl", "--fatal-warnings", src, "-o", obj], check=True)
        subprocess.run([OBJCOPY, "-O", "binary", "-j", ".text", obj, bin_], check=True)
        data = open(bin_, "rb").read()

    if len(data) != 4 * len(lines):
        sys.exit(f"expected {len(lines)} words, got {len(data) // 4}")

    out = ["// Generated by gen_vectors.py from vectors.txt; do not edit.\n"]
    for i, line in enumerate(lines):
        word = int.from_bytes(data[4 * i : 4 * i + 4], "big")
        out.append(f'PPC_VECTOR("{line}", 0x{word:08X})\n')
    with open(os.path.join(HERE, "vectors.inc"), "w") as f:
        f.writelines(out)
    print(f"wrote {len(lines)} vectors")


if __name__ == "__main__":
    main()
